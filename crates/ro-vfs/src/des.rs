type Block = [u8; 8];

fn permute(src: &Block, table: &[u8; 64]) -> Block {
    let mut out = [0u8; 8];
    for (i, &t) in table.iter().enumerate() {
        let j = (t - 1) as usize;
        if src[j >> 3] & MASK[j & 7] != 0 {
            out[i >> 3] |= MASK[i & 7];
        }
    }
    out
}

fn expand(s: &Block) -> Block {
    [
        ((s[7] << 5) | (s[4] >> 3)) & 0x3f,
        ((s[4] << 1) | (s[5] >> 7)) & 0x3f,
        ((s[4] << 5) | (s[5] >> 3)) & 0x3f,
        ((s[5] << 1) | (s[6] >> 7)) & 0x3f,
        ((s[5] << 5) | (s[6] >> 3)) & 0x3f,
        ((s[6] << 1) | (s[7] >> 7)) & 0x3f,
        ((s[6] << 5) | (s[7] >> 3)) & 0x3f,
        ((s[7] << 1) | (s[4] >> 7)) & 0x3f,
    ]
}

fn sbox(s: &Block) -> Block {
    let mut out = [0u8; 8];
    for i in 0..4 {
        out[i] = (S_TABLE[i][s[i * 2] as usize] & 0xf0) | (S_TABLE[i][s[i * 2 + 1] as usize] & 0x0f);
    }
    out
}

fn transpose(s: &Block) -> Block {
    let mut out = [0u8; 8];
    for (i, &t) in TP_TABLE.iter().enumerate() {
        let j = (t - 1) as usize;
        if s[j >> 3] & MASK[j & 7] != 0 {
            out[(i >> 3) + 4] |= MASK[i & 7];
        }
    }
    out
}

fn decrypt_block(block: &mut [u8]) {
    let src: Block = (&*block).try_into().unwrap();
    let mut b = permute(&src, &IP_TABLE);
    let f = transpose(&sbox(&expand(&b)));
    for i in 0..4 {
        b[i] ^= f[i + 4];
    }
    block.copy_from_slice(&permute(&b, &FP_TABLE));
}

fn substitution(v: u8) -> u8 {
    match v {
        0x00 => 0x2b,
        0x2b => 0x00,
        0x6c => 0x80,
        0x80 => 0x6c,
        0x01 => 0x68,
        0x68 => 0x01,
        0x48 => 0x77,
        0x77 => 0x48,
        0x60 => 0xff,
        0xff => 0x60,
        0xb9 => 0xc0,
        0xc0 => 0xb9,
        0xfe => 0xeb,
        0xeb => 0xfe,
        v => v,
    }
}

fn shuffle_dec(b: &mut [u8]) {
    let s: Block = b.try_into().unwrap();
    b.copy_from_slice(&[s[3], s[4], s[6], s[0], s[1], s[2], s[5], substitution(s[7])]);
}

/// Flag 0x04: only the first 20 blocks are encrypted.
pub fn decode_header(buf: &mut [u8]) {
    for block in buf.chunks_exact_mut(8).take(20) {
        decrypt_block(block);
    }
}

/// Flag 0x02: first 20 blocks encrypted, then one in every `cycle` blocks, with
/// every 7th remaining plaintext block shuffled. `comp_len` is the entry's compressed size.
pub fn decode_mixed(buf: &mut [u8], comp_len: u32) {
    let digits = comp_len.max(1).ilog10() + 1;
    let cycle = match digits {
        0..=2 => 1,
        3..=4 => digits + 1,
        5..=6 => digits + 9,
        _ => digits + 15,
    } as usize;

    let mut j = 0usize;
    for (i, block) in buf.chunks_exact_mut(8).enumerate() {
        if i < 20 || i % cycle == 0 {
            decrypt_block(block);
            continue;
        }
        if j % 7 == 0 && j != 0 {
            shuffle_dec(block);
        }
        j += 1;
    }
}
