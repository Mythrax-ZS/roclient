use std::{collections::HashMap, sync::OnceLock};

use crate::generated;

#[derive(Clone, Copy, Debug)]
pub enum PacketLen {
    Fixed(usize),
    /// u16 total length at offset 2.
    Variable,
}

pub trait PacketTable: Send + Sync {
    fn len_of(&self, opcode: u16) -> Option<PacketLen>;
}

/// A client -> server packet as the map server's packet db describes it.
#[derive(Debug)]
pub struct ClientPacket {
    pub opcode: u16,
    /// -1 = variable
    pub len: i32,
    /// rAthena handler name without the `clif_parse_` prefix; empty for struct-only packets.
    pub handler: &'static str,
    /// Field offsets the server reads, in handler order.
    pub pos: &'static [u16],
    pub seq: usize,
}

/// Server -> client lengths generated by tools/packetgen.
#[derive(Clone, Copy, Default)]
pub struct ServerTable;

fn server_map() -> &'static HashMap<u16, PacketLen> {
    static MAP: OnceLock<HashMap<u16, PacketLen>> = OnceLock::new();
    MAP.get_or_init(|| {
        generated::SERVER
            .iter()
            .map(|&(op, len)| (op, if len < 0 { PacketLen::Variable } else { PacketLen::Fixed(len as usize) }))
            .collect()
    })
}

impl PacketTable for ServerTable {
    fn len_of(&self, opcode: u16) -> Option<PacketLen> {
        server_map().get(&opcode).copied()
    }
}

/// The opcode the server currently expects for a handler (the most recent registration).
pub fn client_packet(handler: &str) -> &'static ClientPacket {
    generated::CLIENT
        .iter()
        .filter(|p| p.handler == handler)
        .max_by_key(|p| p.seq)
        .unwrap_or_else(|| panic!("no client packet for handler {handler} at PACKETVER {}", generated::PACKETVER))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_layouts() {
        let t = ServerTable;
        assert!(matches!(t.len_of(generated::id::ZC_ACCEPT_ENTER), Some(PacketLen::Fixed(13))));
        assert!(matches!(t.len_of(generated::id::HC_NOTIFY_ZONESVR), Some(PacketLen::Fixed(156))));
        assert!(matches!(t.len_of(generated::id::AC_ACCEPT_LOGIN), Some(PacketLen::Variable)));
        let enter = client_packet("WantToConnection");
        assert_eq!((enter.opcode, enter.len), (0x0436, 23));
        assert_eq!(client_packet("LoadEndAck").opcode, 0x007d);
    }
}
