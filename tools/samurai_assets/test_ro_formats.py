"""Binary fixtures target compatibility details and reject truncated assets."""

import copy
from pathlib import Path
import struct
import tempfile
import unittest

from ro_formats import FormatError, read_act, read_spr, validate_pair, write_act, write_spr


class FormatsTest(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.spr = Path(self.directory.name) / "fixture.spr"
        self.act = Path(self.directory.name) / "fixture.act"
        self.palette = bytes((v % 256 for v in range(1024)))

    def test_indexed_fixture_byte_order_and_zero_runs(self):
        pixels = bytes([0, 0, 2, 3, 0, 4])
        write_spr(self.spr, [dict(width=3, height=2, pixels=pixels)], self.palette)
        # Authored fixture, not generated by the decoder/encoder helpers.
        expected = b"SP\x01\x02\x01\x00\x00\x00\x03\x00\x02\x00\x07\x00\x00\x02\x02\x03\x00\x01\x04"
        self.assertEqual(self.spr.read_bytes(), expected + self.palette)
        parsed = read_spr(expected + self.palette)
        self.assertEqual(parsed["images"][0]["pixels"], pixels)

    def test_long_zero_run_crosses_255(self):
        pixels = bytes(600)
        write_spr(self.spr, [dict(width=30, height=20, pixels=pixels)], self.palette)
        self.assertEqual(self.spr.read_bytes()[14:20], b"\x00\xff\x00\xff\x00\x5a")
        self.assertEqual(read_spr(self.spr)["images"][0]["pixels"], pixels)

    def test_truecolor_bottom_up_abgr_and_translucency(self):
        pixels = bytes([1, 2, 3, 4, 5, 6, 7, 8, 10, 20, 30, 40, 50, 60, 70, 80])
        write_spr(self.spr, [dict(width=2, height=2, pixels=pixels, sprite_type=1)])
        expected_payload = bytes([40, 30, 20, 10, 80, 70, 60, 50, 4, 3, 2, 1, 8, 7, 6, 5])
        self.assertEqual(self.spr.read_bytes()[:12], b"SP\x01\x02\x00\x00\x01\x00\x02\x00\x02\x00")
        self.assertEqual(self.spr.read_bytes()[12:28], expected_payload)
        self.assertEqual(read_spr(self.spr)["images"][0]["pixels"], pixels)

    def action(self, **layer_changes):
        layer = dict(sprite_index=0, sprite_type=0, x=-2, y=-40, width=3, height=2)
        layer.update(layer_changes)
        return dict(interval=4.0, frames=[dict(layers=[layer], anchors=[dict(x=0, y=-65)])])

    def test_act_authored_binary_fixture(self):
        action = self.action()
        write_act(self.act, [action])
        expected = b"AC\x05\x02\x01\x00" + bytes(10)
        expected += struct.pack("<I", 1) + bytes(32) + struct.pack("<I", 1)
        expected += struct.pack("<iiii", -2, -40, 0, 0) + b"\xff\xff\xff\xff"
        expected += struct.pack("<ffiiii", 1.0, 1.0, 0, 0, 3, 2)
        expected += struct.pack("<iiIiii", -1, 1, 0, 0, -65, 0)
        expected += struct.pack("<if", 0, 4.0)
        self.assertEqual(self.act.read_bytes(), expected)
        parsed = read_act(expected)
        self.assertEqual(parsed["actions"][0]["frames"][0]["anchors"][0]["y"], -65)

    def test_all_player_actions_and_cross_file_reference(self):
        write_spr(self.spr, [dict(width=3, height=2, pixels=bytes([1] * 6))], self.palette)
        actions = [self.action() for _ in range(104)]
        write_act(self.act, actions)
        result = validate_pair(self.spr, self.act, require_player=True)
        self.assertTrue(result["valid"])
        self.assertEqual(result["actions"], 104)
        self.assertEqual(result["frames"], 104)
        actions[-1]["frames"][0]["layers"][0]["sprite_index"] = 1
        write_act(self.act, actions)
        with self.assertRaisesRegex(FormatError, "does not exist"):
            validate_pair(self.spr, self.act)

    def test_type_relative_indices_and_dimensions(self):
        write_spr(self.spr, [dict(width=3, height=2, pixels=bytes([1] * 6)),
                             dict(width=1, height=1, sprite_type=1, pixels=b"\xff\x00\x00\xff")], self.palette)
        write_act(self.act, [self.action(sprite_type=1, width=1, height=1)])
        self.assertEqual(validate_pair(self.spr, self.act)["used_images"], 1)
        write_act(self.act, [self.action(sprite_type=1)])
        with self.assertRaisesRegex(FormatError, "dimensions differ"):
            validate_pair(self.spr, self.act)

    def test_event_and_nontrivial_layer_fields(self):
        action = self.action(mirror=True, rotation=30, scale_x=0.5, scale_y=1.5,
                             color=(100, 150, 200, 240))
        action["frames"][0]["sound_id"] = 0
        write_act(self.act, [action], sounds=["atk"])
        result = read_act(self.act)
        layer = result["actions"][0]["frames"][0]["layers"][0]
        self.assertEqual(result["sounds"], ["atk"])
        self.assertEqual(layer["color"], (100, 150, 200, 240))
        self.assertEqual((layer["scale_x"], layer["scale_y"], layer["rotation"]), (0.5, 1.5, 30))
        self.assertTrue(layer["mirror"])

    def test_reject_truncated_and_trailing_bytes(self):
        write_spr(self.spr, [dict(width=3, height=2, pixels=bytes(6))], self.palette)
        write_act(self.act, [self.action()])
        for path, reader in ((self.spr, read_spr), (self.act, read_act)):
            data = path.read_bytes()
            for cut in (0, 3, 10, len(data) - 1):
                with self.subTest(path=path, cut=cut), self.assertRaises(FormatError):
                    reader(data[:cut])
            with self.assertRaisesRegex(FormatError, "trailing"):
                reader(data + b"junk")

    def test_reject_invalid_inputs_before_writing(self):
        with self.assertRaisesRegex(FormatError, "interval"):
            write_act(self.act, [dict(frames=self.action()["frames"], interval=float("nan"))])
        with self.assertRaisesRegex(FormatError, "sound_id"):
            action = copy.deepcopy(self.action())
            action["frames"][0]["sound_id"] = 0
            write_act(self.act, [action])
        with self.assertRaisesRegex(FormatError, "pixel bytes"):
            write_spr(self.spr, [dict(width=2, height=2, pixels=b"\x01")], self.palette)


if __name__ == "__main__":
    unittest.main()
